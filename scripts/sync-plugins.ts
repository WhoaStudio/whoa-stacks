#!/usr/bin/env bun
/**
 * Regenerates `src/core/registry/generated.ts` from whatever is on disk under
 * `src/plugins/<category>/<id>/plugin.ts`.
 *
 * This exists so that adding a plugin is one folder and nothing else. Discovery
 * could run at startup instead, but a runtime glob does not survive
 * `bun build --compile`, so it happens here and the result is committed.
 *
 * Run: bun run plugins:sync
 */
import { resolve } from "node:path";

import { discoverPlugins } from "../src/core/registry/discover.ts";

const projectRoot = resolve(import.meta.dir, "..");
const pluginsRoot = resolve(projectRoot, "src/plugins");
const outputPath = resolve(projectRoot, "src/core/registry/generated.ts");

const discovered = await discoverPlugins(pluginsRoot);

if (discovered.length === 0) {
  console.error(`No plugins found under ${pluginsRoot}.`);
  process.exit(1);
}

// Sort by category then id so the file is stable across machines.
const sorted = [...discovered].sort((a, b) =>
  a.category === b.category
    ? a.id.localeCompare(b.id)
    : a.category.localeCompare(b.category),
);

const identifier = (id: string): string =>
  id.replace(/[-_](\w)/g, (_, char: string) => char.toUpperCase());

const contents = `// Generated by \`bun run plugins:sync\`. Do not edit by hand.
//
// Adding a plugin means adding a folder under src/plugins/<category>/<id>/ and
// re-running that script. Nothing in src/core/** needs to change.
import type { Plugin } from "../contracts/index.ts";

${sorted.map((plugin) => `import ${identifier(plugin.id)} from "${plugin.importPath}";`).join("\n")}

export const GENERATED_PLUGINS: readonly Plugin[] = [
${sorted.map((plugin) => `  ${identifier(plugin.id)},`).join("\n")}
];
`;

await Bun.write(outputPath, contents);
console.log(`Wrote ${sorted.length} plugin(s) to ${outputPath}`);
